def books() -> dict:
    order = {"入门": 0, "进阶": 1, "高阶": 2}
    rows = sorted(BOOKS, key=lambda b: (order.get(b.get("level"), 9), b.get("order") or 99))
    by_cat: dict[str, list[dict]] = {}
    for b in BOOKS:
        by_cat.setdefault(b["category"], []).append(b)
    cats = [{**c, "books": sorted(by_cat.get(c["key"], []), key=lambda x: x.get("order") or 99),
             "count": len(by_cat.get(c["key"], []))} for c in BOOK_CATEGORIES]
    return {"categories": BOOK_CATEGORIES, "groups": cats, "rows": rows,
            "total": len(BOOKS),
            "levelDist": {lv: sum(1 for b in BOOKS if b.get("level") == lv) for lv in order},
            "note": "书单按原站三大分类整理，附阅读顺序与本书对应到看盘动作的落点"}
